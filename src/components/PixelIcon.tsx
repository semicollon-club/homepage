export type PixelIconName = keyof typeof glyphs

/** '#' 가 이어진 칸을 한 줄짜리 사각형으로 묶어 path 하나로 만듭니다 */
function toPath(rows: Glyph): string {
  let d = ''
  rows.forEach((row, y) => {
    let x = 0
    while (x < row.length) {
      if (row[x] !== '#') {
        x += 1
        continue
      }
      let end = x
      while (end < row.length && row[end] === '#') end += 1
      d += `M${x} ${y}h${end - x}v1h${x - end}z`
      x = end
    }
  })
  return d
}

const paths = Object.fromEntries(
  Object.entries(glyphs).map(([name, rows]) => [name, toPath(rows)]),
) as Record<PixelIconName, string>

interface PixelIconProps {
  name: PixelIconName
  /** 16의 배수여야 픽셀이 뭉개지지 않습니다 */
  size?: 16 | 32 | 48
}

function PixelIcon({ name, size = 32 }: PixelIconProps) {
  return (
    <svg
      className="pixel-icon"
      width={size}
      height={size}
      viewBox="0 0 16 16"
      aria-hidden="true"
      focusable="false"
      shapeRendering="crispEdges"
    >
      <path d={paths[name]} fill="currentColor" />
    </svg>
  )
}

export default PixelIcon
